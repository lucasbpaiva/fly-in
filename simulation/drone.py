from collections import deque
from graph import Zone, Connection


class Drone:
    """Represents a single agent in the routing simulation.

    Encapsulates its physical location, completion state, and the sequence
    of moves generated by the pathfinding algorithm.
    """
    def __init__(self, drone_id: str, initial_location: Zone) -> None:
        """Initialize the drone's state.

        Args:
            drone_id: The unique string identifier (e.g., 'D1').
            initial_location: The Zone object where the drone spawns.
        """
        self.id: str = drone_id
        self.location: Zone | Connection = initial_location
        self.is_finished: bool = False
        self.planned_path: deque[Zone | Connection] = deque()
